int custom_img(void)
{
    printf("Printing custom Image \r\n");

    DEV_Module_Init();

    printf("e-Paper Init and Clear...\r\n");
    EPD_1IN54_V2_Init();
    EPD_1IN54_V2_Clear();
    DEV_Delay_ms(500);

    UBYTE *BlackImage;

    UWORD Imagesize = ((EPD_1IN54_V2_WIDTH % 8 == 0) ?
                      (EPD_1IN54_V2_WIDTH / 8) :
                      (EPD_1IN54_V2_WIDTH / 8 + 1))
                      * EPD_1IN54_V2_HEIGHT;

    BlackImage = (UBYTE *)malloc(Imagesize);

    if (BlackImage == NULL) {
        printf("Memory allocation failed\r\n");
        return -1;
    }

    printf("Paint_NewImage\r\n");

    Paint_NewImage(BlackImage,
                   EPD_1IN54_V2_WIDTH,
                   EPD_1IN54_V2_HEIGHT,
                   270, WHITE);

    Paint_SelectImage(BlackImage);
    Paint_Clear(WHITE);

    // 🔽 Draw your image
    Paint_DrawBitMap(image_data);

    // FIX inversion
    for (int i = 0; i < Imagesize; i++) {
        BlackImage[i] = ~BlackImage[i];
    }

    // 🔽 IMPORTANT: Send buffer to display
    EPD_1IN54_V2_Display(BlackImage);

    DEV_Delay_ms(2000);

    // Optional but recommended
    EPD_1IN54_V2_Sleep();

    free(BlackImage);

    return 0;
}

